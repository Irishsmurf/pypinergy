#!/usr/bin/env python3
"""Automated API schema documentation generator.

Introspects the dataclasses in src/pypinergy/models.py to generate
markdown reference tables for response fields.
"""

import ast
import os
import sys
from typing import Any, Dict, List


def generate_markdown(models_file_path: str) -> str:
    if not os.path.exists(models_file_path):
        print(f"Error: {models_file_path} not found.", file=sys.stderr)
        sys.exit(1)

    with open(models_file_path, "r", encoding="utf-8") as f:
        tree = ast.parse(f.read())

    classes: List[Dict[str, Any]] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.ClassDef):
            continue

        # Check if it's a dataclass
        is_dc = False
        for dec in node.decorator_list:
            if isinstance(dec, ast.Name) and dec.id == "dataclass":
                is_dc = True
                break
            elif (
                isinstance(dec, ast.Call)
                and isinstance(dec.func, ast.Name)
                and dec.func.id == "dataclass"
            ):
                is_dc = True
                break

        if not is_dc:
            continue

        class_name = node.name
        class_doc = ast.get_docstring(node) or ""
        class_doc = " ".join(class_doc.strip().split())

        fields = []
        for i, stmt in enumerate(node.body):
            if isinstance(stmt, ast.AnnAssign):
                if not isinstance(stmt.target, ast.Name):
                    continue
                field_name = stmt.target.id
                field_type = ast.unparse(stmt.annotation)

                field_doc = ""
                if i + 1 < len(node.body):
                    next_stmt = node.body[i + 1]
                    if isinstance(next_stmt, ast.Expr):
                        if hasattr(ast, "Constant") and isinstance(next_stmt.value, ast.Constant):
                            val = next_stmt.value.value
                            if isinstance(val, str):
                                field_doc = val
                        elif isinstance(next_stmt.value, ast.Str):
                            field_doc = str(next_stmt.value.s)

                field_doc = " ".join(field_doc.strip().split())
                fields.append((field_name, field_type, field_doc))

        classes.append({"name": class_name, "docstring": class_doc, "fields": fields})

    # Sort classes by name for consistency
    classes.sort(key=lambda c: str(c["name"]))

    # Generate Markdown
    md = []
    md.append("# Pinergy API Models Schema")
    md.append("")
    md.append(
        "This document was automatically generated by running `python scripts/generate_schema_docs.py`."
    )
    md.append("It documents all API response dataclasses defined in `src/pypinergy/models.py`.")
    md.append("")
    md.append("## Table of Contents")
    for cls in classes:
        anchor = str(cls["name"]).lower()
        md.append(f"- [{cls['name']}](#{anchor})")
    md.append("")
    md.append("---")
    md.append("")

    for cls in classes:
        md.append(f"## {cls['name']}")
        if cls["docstring"]:
            md.append(cls["docstring"])
            md.append("")

        md.append("| Field Name | Type | Description |")
        md.append("| :--- | :--- | :--- |")
        if not cls["fields"]:
            md.append("| *No fields* | | |")
        else:
            for f_name, f_type, f_doc in cls["fields"]:
                # Escape pipe characters in type string if any
                f_type_clean = f_type.replace("|", "\\|")
                md.append(f"| `{f_name}` | `{f_type_clean}` | {f_doc} |")
        md.append("")
        md.append("---")
        md.append("")

    return "\n".join(md)


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Generate API schema markdown documentation.")
    parser.add_argument(
        "--models-path",
        default="src/pypinergy/models.py",
        help="Path to models.py file (default: src/pypinergy/models.py)",
    )
    parser.add_argument(
        "--output", help="Path to save the generated markdown (prints to stdout if not specified)"
    )
    args = parser.parse_args()

    markdown_content = generate_markdown(args.models_path)

    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(markdown_content)
        print(f"Successfully generated schema documentation at {args.output}")
    else:
        print(markdown_content)


if __name__ == "__main__":
    main()
